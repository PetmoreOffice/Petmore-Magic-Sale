-- ตำแหน่งเดิม MANAGER (ผู้จัดการคลัง) และ WH (พนักงานคลัง) ทำงานคลัง จึงย้ายเป็น CHECKER
-- เปลี่ยนแค่ชื่อตำแหน่ง สิทธิ์เก็บรายคนอยู่แล้ว ไม่แตะ ผู้ดูแลระบบปรับสิทธิ์รายคนเองได้
UPDATE "User" SET "roleCode" = 'CHECKER' WHERE "roleCode" IN ('MANAGER', 'WH');
