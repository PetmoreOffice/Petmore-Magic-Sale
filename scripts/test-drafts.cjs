const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync('apps/web/src/lib/drafts.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {} };
vm.runInNewContext(compiled, context);
const { createDraftStore, clearDrafts, draftKeyFor } = context.exports;
const checks = createDraftStore(), returns = createDraftStore(), orders = createDraftStore();
checks.set(draftKeyFor('A', 'SO-1'), { count: 3 });
returns.set(draftKeyFor('A', 'free'), { qty: 5 });
orders.set('A', { qty: 2 });
assert.equal(checks.get(draftKeyFor('B', 'SO-1')), undefined);
assert.equal(returns.get(draftKeyFor('B', 'free')), undefined);
assert.notEqual(draftKeyFor('A:B', 'C'), draftKeyFor('A', 'B:C'));
clearDrafts();
for (const store of [checks, returns, orders]) assert.equal(store.size, 0);
assert.equal(createDraftStore().size, 0);
console.log('Passed draft isolation, collision prevention and clearing across all storefront draft stores.');
